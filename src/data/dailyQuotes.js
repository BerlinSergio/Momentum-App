/**
 * Calculates the day of the year (1 - 366) in UTC-normalized time
 * to prevent daylight saving time / timezone skew.
 */
export function getDayOfYear(date = new Date()) {
  const d = date instanceof Date ? date : new Date(date);
  if (isNaN(d.getTime())) return 1;
  const utcDate = Date.UTC(d.getFullYear(), d.getMonth(), d.getDate());
  const utcStart = Date.UTC(d.getFullYear(), 0, 1);
  return Math.floor((utcDate - utcStart) / 86400000) + 1;
}

/**
 * Returns the index in DAILY_QUOTES corresponding to a specific calendar date.
 * Cycles sequentially through the quote array every 24 hours.
 */
export function getDailyQuoteIndex(date = new Date()) {
  const dayOfYear = getDayOfYear(date);
  return (dayOfYear - 1) % DAILY_QUOTES.length;
}

/**
 * Retrieves the daily radiance quote for the specified calendar date.
 */
export function getDailyQuote(date = new Date()) {
  const index = getDailyQuoteIndex(date);
  return DAILY_QUOTES[index] || DAILY_QUOTES[0];
}

